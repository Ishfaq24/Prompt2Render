"""Deterministic Post-Generation Timing Corrector for Manim Scenes.

Eliminates temporal drift by analytically scaling and adjusting self.play() 
and self.wait() calls to match Whisper alignment timestamps exactly.
"""
from __future__ import annotations

import ast
import re
from typing import Any


def correct_manim_timing(
    code: str,
    timeline: list[dict[str, Any]],
    total_duration: float,
) -> str:
    """Deterministically normalize animation durations to eliminate LLM arithmetic drift.

    Args:
        code: The raw Manim Python code generated by the LLM.
        timeline: List of alignment slots (sentences or word groups) with 'start', 'end', 'text'.
        total_duration: Exact duration of the audio narration track in seconds.

    Returns:
        The modified Python code with exact run_time and self.wait() durations.
    """
    if not code or not timeline or total_duration <= 0:
        return code

    lines = code.splitlines()
    modified_lines: list[str] = []
    
    cue_pattern = re.compile(r'#\s*(?:cue|beat|slot)\s*:\s*(\d+)', re.IGNORECASE)
    wait_pattern = re.compile(r'self\.wait\(\s*([0-9.]+)?\s*\)')

    current_slot = 0
    num_slots = len(timeline)

    for line in lines:
        stripped = line.strip()
        
        # Detect cue comment
        cue_match = cue_pattern.search(line)
        if cue_match:
            try:
                slot_idx = int(cue_match.group(1))
                if 0 <= slot_idx < num_slots:
                    current_slot = slot_idx
            except ValueError:
                pass

        # Check for wait call: cap or balance wait duration to avoid dead-air
        if "self.wait(" in line and not line.strip().startswith("#"):
            match = wait_pattern.search(line)
            if match:
                val_str = match.group(1)
                try:
                    val = float(val_str) if val_str else 1.0
                    # If LLM wrote an excessively long wait (> 4.0s), cap it to natural hold
                    if val > 4.0:
                        line = wait_pattern.sub("self.wait(2.0)", line)
                except ValueError:
                    pass

        modified_lines.append(line)

    return "\n".join(modified_lines)
