"""Stage 4 - the upload packet.

Writes ``out/upload.md`` with:

- title options
- description
- chapters
- tags
- output-file references
- a final human pre-upload checklist

Nothing here publishes automatically. The final human review is deliberate:
the upload packet is a release checklist, not an autonomous publishing step.
"""
from __future__ import annotations

import re
from pathlib import Path

from . import assemble
from .project import Script


TEMPLATE = """# Upload packet — {title}

## Title options

Pick one. Keep the final title concise and accurate.

1. {title}
2. {title} — Explained Visually
3. How {short} Actually Works

## Description

{hook}

### Chapters

{chapters}

---

Timestamps and animations by me. Source notes and slides: <link>

Corrections welcome in the comments — I pin useful corrections.

#computerscience #{tag1} #{tag2}

## Tags

{tags}

## Files

- video ....... `out/final.mp4`
- captions .... `out/captions.srt`
- thumbnail ... `out/thumb_source.png`

## Pre-upload checks

- [ ] Watched the video end to end at 1x.
- [ ] Checked every frame for text overlapping shapes, clipping, or
      unreadable labels.
- [ ] Checked the first 30 seconds: does it open on the actual viewer
      question rather than a generic greeting?
- [ ] Checked audio for clipping, sudden level changes, noise, or unnatural
      pauses between sections.
- [ ] Checked captions, especially equations, symbols, acronyms, and
      technical terminology.
- [ ] Checked that captions remain synchronized with the spoken audio.
- [ ] Checked the thumbnail at approximately 120px wide: one clear idea,
      readable text, no unnecessary clutter.
- [ ] Verified the title and description accurately represent the actual
      video.
- [ ] If synthetic or altered content is present, check YouTube Studio's
      current "altered or synthetic content" disclosure requirements and
      make the appropriate disclosure.
- [ ] Confirmed that the video contains meaningful original educational
      explanation, examples, analysis, or presentation rather than merely
      repackaging automatically generated material.
- [ ] Checked that the ending points naturally toward the specific next
      learning step or video.
- [ ] Verified all source links, citations, and attribution notes.
- [ ] Confirmed that no placeholder text such as `<link>` remains.
- [ ] Confirmed that no internal paths, debug messages, or development notes
      accidentally appear in the public description.

## Release notes

Spoken word count: {words} (~{minutes:.1f} min at 140 wpm)

Sections: {nsections}

Topic: {topic}

Generated by Prompt2Render. Final publication decision remains manual.
"""


def _clean_inline(text: str, fallback: str = "") -> str:
    """Collapse whitespace for metadata intended for one-line display."""
    value = re.sub(r"\s+", " ", str(text or "")).strip()
    return value or fallback


def _short_title(title: str) -> str:
    """Produce a compact subject phrase for the alternative title."""
    short = re.split(r"[—–:-]", title, maxsplit=1)[0]
    short = _clean_inline(short, title)

    # Avoid producing an excessively long "How ... Actually Works" title.
    if len(short) > 50:
        short = short[:50].rsplit(" ", 1)[0]

    return short


def _hook(script: Script) -> str:
    """Extract a short opening sentence for the description."""
    if not script.sections:
        return ""

    narration = script.sections[0].narration.strip()

    if not narration:
        return ""

    # Prefer the first paragraph/sentence rather than dumping a large block.
    first = re.split(r"(?<=[.!?])\s+", narration, maxsplit=1)[0]
    return _clean_inline(first[:300])


def _topic_words(script: Script) -> list[str]:
    """Extract conservative topic words for hashtags/tags."""
    source = _clean_inline(
        script.meta.get("topic", script.title),
        script.title,
    )

    words = re.findall(
        r"[A-Za-z0-9][A-Za-z0-9+#.-]*",
        source,
    )

    ignored = {
        "the",
        "and",
        "for",
        "with",
        "from",
        "into",
        "using",
        "about",
        "this",
        "that",
        "how",
        "what",
        "why",
    }

    return [
        word.lower()
        for word in words
        if len(word) > 2 and word.lower() not in ignored
    ]


def _tags(script: Script) -> str:
    """Build a small, stable tag set from the topic."""
    topic_words = _topic_words(script)

    defaults = [
        "computer science",
        "explained",
        "visual explanation",
        "tutorial",
    ]

    values: list[str] = []

    for value in topic_words + defaults:
        value = _clean_inline(value)

        if not value:
            continue

        if value.lower() not in {
            existing.lower()
            for existing in values
        }:
            values.append(value)

    return ", ".join(values)


def _hashtags(script: Script) -> tuple[str, str]:
    """Return two conservative hashtag tokens."""
    words = _topic_words(script)

    valid = [
        re.sub(r"[^A-Za-z0-9_]", "", word)
        for word in words
    ]

    valid = [
        word
        for word in valid
        if word
    ]

    tag1 = valid[0] if valid else "explained"
    tag2 = valid[1] if len(valid) > 1 else "tutorial"

    return tag1, tag2


def _validate_chapters(script: Script) -> str:
    """Generate chapters and make sure they are usable."""
    chapters = assemble.chapters(script)

    if not chapters:
        return "00:00 Introduction"

    return chapters


def _validate_output_references(proj: Path) -> list[str]:
    """Report expected release artifacts that do not yet exist.

    Missing artifacts are warnings in the packet rather than hard failures:
    ``upload`` can legitimately be generated before ``finish``.
    """
    expected = [
        proj / "out" / "final.mp4",
        proj / "out" / "captions.srt",
        proj / "out" / "thumb_source.png",
    ]

    return [
        str(path)
        for path in expected
        if not path.exists()
    ]


def build_packet(proj: Path, script: Script) -> Path:
    """Build ``out/upload.md`` for a completed or nearly completed project."""
    if not script.sections:
        raise SystemExit(
            "[prompt2render] cannot create upload packet: script has no sections"
        )

    title = _clean_inline(
        script.title,
        "Untitled video",
    )

    short = _short_title(title)
    hook = _hook(script)
    chapters = _validate_chapters(script)

    tags = _tags(script)
    tag1, tag2 = _hashtags(script)

    topic = _clean_inline(
        script.meta.get("topic", title),
        title,
    )

    words = script.word_count
    minutes = words / 140 if words else 0.0

    dst = proj / "out" / "upload.md"
    dst.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    content = TEMPLATE.format(
        title=title,
        short=short,
        hook=hook or "Add a concise opening description here.",
        chapters=chapters,
        tags=tags,
        tag1=tag1,
        tag2=tag2,
        words=words,
        minutes=minutes,
        nsections=len(script.sections),
        topic=topic,
    )

    missing = _validate_output_references(proj)

    if missing:
        content += (
            "\n## Build artifacts not yet present\n\n"
            "The packet was generated before all release artifacts existed. "
            "Run the appropriate build/finish stage before publishing.\n\n"
        )

        for path in missing:
            content += f"- [ ] `{path}`\n"

    # Explicitly surface unresolved placeholders so they cannot be missed.
    placeholders = [
        token
        for token in ("<link>", "Untitled video")
        if token in content
    ]

    if placeholders:
        content += (
            "\n## Placeholder audit\n\n"
            "The following placeholders still need human attention:\n\n"
        )

        for placeholder in placeholders:
            content += f"- [ ] `{placeholder}`\n"

    dst.write_text(
        content,
        encoding="utf-8",
    )

    return dst