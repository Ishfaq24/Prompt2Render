"""Stage 4 - the upload packet.

Writes ``out/upload.md`` with:

- title options
- description
- chapters
- tags
- output-file references
- a final human pre-upload checklist

Nothing here publishes automatically. The final human review is deliberate:
the upload packet is a release checklist, not an autonomous publishing step.
"""
from __future__ import annotations

import re
from pathlib import Path

from . import assemble
from .project import Script


TEMPLATE = """# Upload packet — {title}

## Title options

Pick one. Keep the final title concise and accurate.

1. {title}
2. {title} — Explained Visually
3. How {short} Actually Works

## Description

{hook}

### Chapters

{chapters}

---

Timestamps and animations by me. Source notes and slides: <link>

Corrections welcome in the comments — I pin useful corrections.

#computerscience #{tag1} #{tag2}

## Tags

{tags}

## Files

- video ....... `out/final.mp4`
- captions .... `out/captions.srt`
- thumbnail ... `out/thumb_source.png`

## Pre-upload checks

- [ ] Watched the video end to end at 1x.
- [ ] Checked every frame for text overlapping shapes, clipping, or
      unreadable labels.
- [ ] Checked the first 30 seconds: does it open on the actual viewer
      question rather than a generic greeting?
- [ ] Checked audio for clipping, sudden level changes, noise, or unnatural
      pauses between sections.
- [ ] Checked captions, especially equations, symbols, acronyms, and
      technical terminology.
- [ ] Checked that captions remain synchronized with the spoken audio.
- [ ] Checked the thumbnail at approximately 120px wide: one clear idea,
      readable text, no unnecessary clutter.
- [ ] Verified the title and description accurately represent the actual
      video.
- [ ] If synthetic or altered content is present, check YouTube Studio's
      current "altered or synthetic content" disclosure requirements and
      make the appropriate disclosure.
- [ ] Confirmed that the video contains meaningful original educational
      explanation, examples, analysis, or presentation rather than merely
      repackaging automatically generated material.
- [ ] Checked that the ending points naturally toward the specific next
      learning step or video.
- [ ] Verified all source links, citations, and attribution notes.
- [ ] Confirmed that no placeholder text such as `<link>` remains.
- [ ] Confirmed that no internal paths, debug messages, or development notes
      accidentally appear in the public description.

## Release notes

Spoken word count: {words} (~{minutes:.1f} min at 140 wpm)

Sections: {nsections}

Topic: {topic}

Generated by Prompt2Render. Final publication decision remains manual.
"""


def _clean_inline(text: str, fallback: str = "") -> str:
    """Collapse whitespace for metadata intended for one-line display."""
    value = re.sub(r"\s+", " ", str(text or "")).strip()
    return value or fallback


def _short_title(title: str) -> str:
    """Produce a compact subject phrase for the alternative title."""
    short = re.split(r"[—–:-]", title, maxsplit=1)[0]
    short = _clean_inline(short, title)

    # Avoid producing an excessively long "How ... Actually Works" title.
    if len(short) > 50:
        short = short[:50].rsplit(" ", 1)[0]

    return short


def _hook(script: Script) -> str:
    """Extract a short opening sentence for the description."""
    if not script.sections:
        return ""

    narration = script.sections[0].narration.strip()

    if not narration:
        return ""

    # Prefer the first paragraph/sentence rather than dumping a large block.
    first = re.split(r"(?<=[.!?])\s+", narration, maxsplit=1)[0]
    return _clean_inline(first[:300])


def _topic_words(script: Script) -> list[str]:
    """Extract conservative topic words for hashtags/tags."""
    source = _clean_inline(
        script.meta.get("topic", script.title),
        script.title,
    )

    words = re.findall(
        r"[A-Za-z0-9][A-Za-z0-9+#.-]*",
        source,
    )

    ignored = {
        "the",
        "and",
        "for",
        "with",
        "from",
        "into",
        "using",
        "about",
        "this",
        "that",
        "how",
        "what",
        "why",
    }

    return [
        word.lower()
        for word in words
        if len(word) > 2 and word.lower() not in ignored
    ]


def _tags(script: Script) -> str:
    """Build a small, stable tag set from the topic."""
    topic_words = _topic_words(script)

    defaults = [
        "computer science",
        "explained",
        "visual explanation",
        "tutorial",
    ]

    values: list[str] = []

    for value in topic_words + defaults:
        value = _clean_inline(value)

        if not value:
            continue

        if value.lower() not in {
            existing.lower()
            for existing in values
        }:
            values.append(value)

    return ", ".join(values)


def _hashtags(script: Script) -> tuple[str, str]:
    """Return two conservative hashtag tokens."""
    words = _topic_words(script)

    valid = [
        re.sub(r"[^A-Za-z0-9_]", "", word)
        for word in words
    ]

    valid = [
        word
        for word in valid
        if word
    ]

    tag1 = valid[0] if valid else "explained"
    tag2 = valid[1] if len(valid) > 1 else "tutorial"

    return tag1, tag2


def _validate_chapters(script: Script) -> str:
    """Generate chapters and make sure they are usable."""
    chapters = assemble.chapters(script)

    if not chapters:
        return "00:00 Introduction"

    return chapters


def _validate_output_references(proj: Path) -> list[str]:
    """Report expected release artifacts that do not yet exist.

    Missing artifacts are warnings in the packet rather than hard failures:
    ``upload`` can legitimately be generated before ``finish``.
    """
    expected = [
        proj / "out" / "final.mp4",
        proj / "out" / "captions.srt",
        proj / "out" / "thumb_source.png",
    ]

    return [
        str(path)
        for path in expected
        if not path.exists()
    ]


def generate_high_ctr_thumbnail(
    proj: Path,
    script: Script,
    dst: Path | None = None,
) -> Path:
    """Composite a high-converting 1280x720 YouTube thumbnail with bold typography."""
    from PIL import Image, ImageDraw, ImageEnhance, ImageFont

    out_dir = proj / "out"
    out_dir.mkdir(parents=True, exist_ok=True)
    target = dst or (out_dir / "thumbnail_master.png")

    candidates = [
        out_dir / "thumbnail.png",
        out_dir / "thumb_source.png",
        proj / "media" / "thumbnail.png",
    ]
    candidates.extend(sorted((proj / "stills").glob("*.png")) if (proj / "stills").is_dir() else [])

    base_img = None
    for cand in candidates:
        if cand.is_file() and cand.stat().st_size > 1024:
            try:
                base_img = Image.open(cand).convert("RGBA")
                break
            except Exception:
                continue

    target_w, target_h = 1280, 720
    if base_img is None:
        base_img = Image.new("RGBA", (target_w, target_h), (15, 23, 42, 255))
    else:
        base_w, base_h = base_img.size
        scale = max(target_w / base_w, target_h / base_h)
        new_w = int(base_w * scale)
        new_h = int(base_h * scale)
        base_img = base_img.resize((new_w, new_h), Image.Resampling.LANCZOS)
        left = (new_w - target_w) // 2
        top = (new_h - target_h) // 2
        base_img = base_img.crop((left, top, left + target_w, top + target_h))

    rgb = base_img.convert("RGB")
    enhancer = ImageEnhance.Contrast(rgb)
    enhanced = enhancer.enhance(1.15)
    base_img = enhanced.convert("RGBA")

    # Dark gradient overlay on the left to make text crisp
    overlay = Image.new("RGBA", (target_w, target_h), (0, 0, 0, 0))
    d_over = ImageDraw.Draw(overlay)
    for x in range(int(target_w * 0.65)):
        alpha = int(190 * (1.0 - (x / (target_w * 0.65))))
        d_over.line([(x, 0), (x, target_h)], fill=(10, 15, 26, alpha))
    composite = Image.alpha_composite(base_img, overlay)

    draw = ImageDraw.Draw(composite)

    font_paths = [
        "C:/Windows/Fonts/arialbd.ttf",
        "C:/Windows/Fonts/segoeuib.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    ]
    title_font = None
    badge_font = None
    for fp in font_paths:
        if Path(fp).is_file():
            try:
                title_font = ImageFont.truetype(fp, 54)
                badge_font = ImageFont.truetype(fp, 22)
                break
            except Exception:
                pass
    if title_font is None:
        title_font = ImageFont.load_default()
        badge_font = ImageFont.load_default()

    # Draw Category Badge
    topic = (script.meta.get("topic") or script.title).upper()
    badge_text = f"  {topic[:26]}  "
    bbox = draw.textbbox((60, 60), badge_text, font=badge_font)
    draw.rounded_rectangle([bbox[0] - 6, bbox[1] - 4, bbox[2] + 6, bbox[3] + 4], radius=6, fill=(56, 139, 253, 230))
    draw.text((60, 60), badge_text, fill=(255, 255, 255), font=badge_font)

    # Wrap title into lines
    words = script.title.split()
    lines: list[str] = []
    curr: list[str] = []
    for w in words:
        curr.append(w)
        if len(" ".join(curr)) > 20:
            lines.append(" ".join(curr[:-1]))
            curr = [w]
    if curr:
        lines.append(" ".join(curr))

    y_offset = 135
    for line in lines[:3]:
        draw.text((64, y_offset + 4), line, fill=(0, 0, 0, 220), font=title_font)
        draw.text((60, y_offset), line, fill=(255, 255, 255), font=title_font)
        y_offset += 66

    composite.convert("RGB").save(str(target), "PNG", quality=95)
    return target


def build_packet(proj: Path, script: Script) -> Path:
    """Build ``out/upload.md`` for a completed or nearly completed project."""
    try:
        generate_high_ctr_thumbnail(proj, script)
    except Exception:
        pass
    if not script.sections:
        raise SystemExit(
            "[prompt2render] cannot create upload packet: script has no sections"
        )

    title = _clean_inline(
        script.title,
        "Untitled video",
    )

    short = _short_title(title)
    hook = _hook(script)
    chapters = _validate_chapters(script)

    tags = _tags(script)
    tag1, tag2 = _hashtags(script)

    topic = _clean_inline(
        script.meta.get("topic", title),
        title,
    )

    words = script.word_count
    minutes = words / 140 if words else 0.0

    dst = proj / "out" / "upload.md"
    dst.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    content = TEMPLATE.format(
        title=title,
        short=short,
        hook=hook or "Add a concise opening description here.",
        chapters=chapters,
        tags=tags,
        tag1=tag1,
        tag2=tag2,
        words=words,
        minutes=minutes,
        nsections=len(script.sections),
        topic=topic,
    )

    missing = _validate_output_references(proj)

    if missing:
        content += (
            "\n## Build artifacts not yet present\n\n"
            "The packet was generated before all release artifacts existed. "
            "Run the appropriate build/finish stage before publishing.\n\n"
        )

        for path in missing:
            content += f"- [ ] `{path}`\n"

    # Surface external media asset attributions
    attributions_file = generate_attributions(proj)
    if attributions_file and attributions_file.exists():
        attrib_text = attributions_file.read_text(encoding="utf-8").strip()
        if attrib_text:
            content += f"\n## Asset Credits & Attributions\n\n{attrib_text}\n"

    # Explicitly surface unresolved placeholders so they cannot be missed.
    placeholders = [
        token
        for token in ("<link>", "Untitled video")
        if token in content
    ]

    if placeholders:
        content += (
            "\n## Placeholder audit\n\n"
            "The following placeholders still need human attention:\n\n"
        )

        for placeholder in placeholders:
            content += f"- [ ] `{placeholder}`\n"

    dst.write_text(
        content,
        encoding="utf-8",
    )

    return dst


def generate_attributions(proj: Path) -> Path | None:
    """Generate out/attributions.md from staged build/assets metadata."""
    import json
    out_dir = proj / "out"
    out_dir.mkdir(parents=True, exist_ok=True)
    attrib_dst = out_dir / "attributions.md"

    # Check for cache metadata matching staged assets
    assets_dir = proj / "build" / "assets"
    if not assets_dir.exists():
        return None

    entries: list[dict[str, str]] = []
    # Search for any .meta.json or provenance logs
    for meta_file in assets_dir.glob("*.meta.json"):
        try:
            with open(meta_file, "r", encoding="utf-8") as f:
                data = json.load(f)
                entries.append(data)
        except Exception:
            continue

    if not entries:
        # Check global cache for staged asset references
        from .assets.cache import DEFAULT_CACHE_DIR
        if DEFAULT_CACHE_DIR.exists():
            for meta_file in DEFAULT_CACHE_DIR.glob("*.meta.json"):
                try:
                    with open(meta_file, "r", encoding="utf-8") as f:
                        data = json.load(f)
                        entries.append(data)
                except Exception:
                    continue

    if not entries:
        return None

    # Deduplicate entries by ID
    seen_ids = set()
    unique_entries = []
    for e in entries:
        eid = e.get("id")
        if eid and eid not in seen_ids:
            seen_ids.add(eid)
            unique_entries.append(e)

    if not unique_entries:
        return None

    lines = [
        "# Media Attributions",
        "",
        "This project uses visual assets from external libraries under their respective free licenses:",
        "",
        "| Asset | Source / Author | License | Link |",
        "|---|---|---|---|",
    ]

    for e in unique_entries:
        title = e.get("title", e.get("id", "Image"))
        author = e.get("author", "Unknown")
        provider = e.get("provider", "Media").title()
        license_name = e.get("license", "Free Content License")
        url = e.get("url", "#")
        author_url = e.get("author_url", "#")
        lines.append(f"| {title} | [{author}]({author_url}) via {provider} | {license_name} | [View]({url}) |")

    lines.append("")
    attrib_dst.write_text("\n".join(lines), encoding="utf-8")
    return attrib_dst