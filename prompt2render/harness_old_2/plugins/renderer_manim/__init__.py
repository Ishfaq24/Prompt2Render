"""Wraps visuals.py::manim_scene() — the opt-in Manim escape hatch, disabled by default
(docs/MIGRATION_INVENTORY.md §5: "deliberately never LLM-driven ... wrap as a disabled-by-default
plugin"). Unlike every other plugin here, prompt2render never batches this over scene_plan — it's always a
single, manual `prompt2render manim <slug> <pyfile> <scene> <index>` call for one hand-authored hero shot.
This plugin mirrors that: it only acts when config names an explicit `py_file`/`scene`/`index` to
render; otherwise it's a no-op, same as the escape hatch being unused on a normal run.
"""
from __future__ import annotations

import os
from pathlib import Path

from ...context import CodeArtifact, RenderArtifact, SceneContext
from ...plugin import Plugin
from ....project import parse_script
from ....visuals import manim_scene


class RendererManimPlugin(Plugin):
    name = "renderer_manim"

    def declare_dependencies(self) -> list[str]:
        return []

    def declare_effects(self) -> list[str]:
        return ["render_artifacts", "check_results"]

    def run(self, context: SceneContext) -> SceneContext:
        # Manual escape hatch mode
        py_file = self.config.get("py_file")
        scene = self.config.get("scene")
        index = self.config.get("index")
        
        script = parse_script(context.prompt)
        
        if py_file and scene and index is not None:
            out = manim_scene(context.project_dir, script, Path(py_file), scene, int(index))
            stem = f"{int(index):02d}"
            context.render_artifacts[stem] = RenderArtifact(stem=stem, outdir=out.parent,
                                                             manifest=[{"png": None, "mp4": str(out)}])
            return context
            
        # Auto mode: render everything generated by generator_manim
        if not context.code_artifacts:
            return context
            
        from .... import cfg
        
        for stem, artifact in context.code_artifacts.items():
            if not artifact.accepted or not artifact.path:
                continue
                
            sec = next((s for s in script.sections if s.stem == stem), None)
            if not sec:
                continue
                
            try:
                out = manim_scene(context.project_dir, script, artifact.path, f"Scene{stem}", sec.index)
                context.render_artifacts[stem] = RenderArtifact(
                    stem=stem, outdir=out.parent, manifest=[{"png": None, "mp4": str(out)}])
            except SystemExit as e:
                # manim_scene calls sys.exit on failure; catch it so we don't crash the whole run
                err = str(e)
                cfg.warn(f"Manim render failed for {stem}: {err}")
                
                # Emit a finding so repair_router can retry the code generation
                from ...finding import Finding, Category, Severity, next_finding_id
                f = Finding(
                    finding_id=next_finding_id("manim"),
                    scene_id=stem,
                    category=Category.SPATIAL,
                    severity=Severity.BLOCKING,
                    message=f"Manim compilation failed:\n{err}"
                )
                context.check_results.setdefault(self.name, []).append(f.as_check_result())
                
                context.render_artifacts[stem] = RenderArtifact(
                    stem=stem, outdir=context.project_dir, manifest=[])
            except Exception as e:
                cfg.warn(f"Manim render failed for {stem}: {e}")
                
                from ...finding import Finding, Category, Severity, next_finding_id
                f = Finding(
                    finding_id=next_finding_id("manim"),
                    scene_id=stem,
                    category=Category.SPATIAL,
                    severity=Severity.BLOCKING,
                    message=f"Manim compilation failed:\n{e}"
                )
                context.check_results.setdefault(self.name, []).append(f.as_check_result())
                
                context.render_artifacts[stem] = RenderArtifact(
                    stem=stem, outdir=context.project_dir, manifest=[])
                
        return context

    def _default_gate(self) -> bool:
        return False

class GeneratorManimPlugin(Plugin):
    """Generates Manim code for a section using an LLM.
    
    This is an experimental alternative to generator_code (which uses scenekit).
    It generates Python code that defines a Manim Scene class.
    """
    name = "generator_manim"

    def declare_dependencies(self) -> list[str]:
        return ["scene_plan", "narration"]

    def declare_effects(self) -> list[str]:
        return ["code_artifacts"]

    def run(self, context: SceneContext) -> SceneContext:
        from ....project import parse_script
        from .... import llm
        from .... import cfg
        from .... import align
        from ...context import CodeArtifact
        
        script = parse_script(context.prompt)
        indices = {e.index for e in context.scene_plan}
        script.sections = [s for s in script.sections if s.index in indices]
        
        plan_by_index = {e.index: e for e in context.scene_plan}
        for sec in script.sections:
            if sec.index in plan_by_index:
                sec.anim = plan_by_index[sec.index].anim

        try:
            if hasattr(llm, "keys"):
                keys = llm.keys()
            else:
                key = os.environ.get("GEMINI_API_KEY", "")
                keys = [key] if key else []
        except SystemExit:
            keys = []
            
        if not keys:
            cfg.warn("No GEMINI_API_KEY found, skipping Manim generation.")
            return context
            
        # Fallbacks for older llm.py
        if hasattr(llm, "model_chain"):
            models = llm.model_chain("P2R_SCENE_MODEL", "gemini-3.7-flash")
            model = models[0]
        else:
            model = os.environ.get("P2R_SCENE_MODEL", "gemini-3.7-flash")
            
        if not hasattr(llm, "complete"):
            if hasattr(llm, "client"):
                client = llm.client(keys[0])
            else:
                try:
                    from openai import OpenAI
                except ImportError:
                    import sys
                    sys.exit("[prompt2render] openai not installed — pip install -r requirements.txt")
                client = OpenAI(
                    api_key=keys[0], 
                    base_url="https://generativelanguage.googleapis.com/v1beta/openai/", 
                    timeout=300.0, 
                    max_retries=2
                )

        outdir = context.project_dir / "build" / "manim"
        outdir.mkdir(parents=True, exist_ok=True)

        for sec in script.sections:
            stem = sec.stem
            py_file = outdir / f"scene_{stem}.py"
            
            # Skip if already generated and we are not in a repair cycle for this scene
            is_repair = stem in context.repair_context
            if py_file.exists() and not is_repair:
                context.code_artifacts[stem] = CodeArtifact(
                    stem=stem, path=py_file, accepted=True)
                continue
                
            cfg.say(f"section {stem}: generating Manim code...")
            
            # Inject repair feedback if available
            msgs = context.repair_context.get(stem, [])
            extra_feedback = ("\n\nPRIOR REPAIR FEEDBACK:\n" + "\n".join(msgs)) if msgs else ""
            
            # Get timing data to tell the model how long to animate
            try:
                data = align.load(context.project_dir, stem)
                sents = data["sentences"]
                duration = sum(s["dur"] for s in sents)
            except Exception:
                duration = 5.0
                
            prompt = (
                f"Write a Manim CE script for this educational video section.\n\n"
                f"Title: {sec.title}\n"
                f"Visual Plan: {sec.anim}\n"
                f"Narration: {sec.narration}\n"
                f"Total Duration: {duration:.1f} seconds\n\n"
                f"Requirements:\n"
                f"1. Use Manim Community Edition (`from manim import *`).\n"
                f"2. Define exactly one class named `Scene{stem}` that inherits from `Scene`.\n"
                f"3. Use `self.play()` and `self.wait()` to pace the animation to match the total duration.\n"
                f"4. DO NOT use `.set_shadow(blur=...)`. It is deprecated/invalid in this version of Manim CE.\n"
                f"5. Output ONLY valid Python code. No markdown fences, no explanations.\n"
            )
            
            if extra_feedback:
                prompt += extra_feedback
            
            try:
                if hasattr(llm, "complete"):
                    code = llm.complete(prompt, max_tokens=4000)
                else:
                    resp = client.chat.completions.create(
                        model=model,
                        messages=[{"role": "user", "content": prompt}]
                    )
                    code = resp.choices[0].message.content if resp.choices else ""
                
                # Strip markdown fences
                code = code.strip()
                import re
                m = re.match(r"^```(?:python)?\s*\n(.*?)\n```\s*$", code, re.S)
                if m:
                    code = m.group(1)
                    
                py_file.write_text(code, encoding="utf-8")
                context.code_artifacts[stem] = CodeArtifact(
                    stem=stem, path=py_file, accepted=True)
                cfg.say(f"section {stem}: Manim code generated")
                
            except Exception as e:
                cfg.warn(f"Manim generation failed for {stem}: {e}")
                context.code_artifacts[stem] = CodeArtifact(
                    stem=stem, path=None, accepted=False)

        return context

    def _default_gate(self) -> bool:
        return False

    # ------------------------------------------------------- repair_router hooks --

    def revert_scene(self, context: SceneContext, stem: str) -> None:
        """Undo this plugin's effect for one section only."""
        py_file = context.project_dir / "build" / "manim" / f"scene_{stem}.py"
        py_file.unlink(missing_ok=True)
        context.code_artifacts.pop(stem, None)
        context.render_artifacts.pop(stem, None)

    def regenerate_one(self, context: SceneContext, stem: str) -> None:
        """Re-run generation for exactly one section using repair feedback."""
        # The main run() loop already checks context.repair_context and skips 
        # existing files appropriately, so we can just call run() again.
        # revert_scene() will have already deleted the bad py_file.
        self.run(context)
